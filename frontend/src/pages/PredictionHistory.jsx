import { useEffect, useState } from "react";

function PredictionHistory() {
  const [predictions, setPredictions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [search, setSearch] = useState("");
  const [filter, setFilter] = useState("ALL");
  const [selectedPrediction, setSelectedPrediction] = useState(null);

  const fetchPredictions = async () => {
    try {
      setLoading(true);
      setError("");

      const response = await fetch("/api/ai-predictions");

      if (!response.ok) {
        throw new Error("Failed to fetch prediction history");
      }

      const data = await response.json();
      setPredictions(data);
    } catch (err) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchPredictions();
  }, []);

  const fraudCount = predictions.filter(
    (item) => item.is_fraud
  ).length;

  const legitimateCount = predictions.filter(
    (item) => !item.is_fraud
  ).length;

  const filteredPredictions = predictions.filter((item) => {
    const matchesSearch = item.id
      .toLowerCase()
      .includes(search.toLowerCase());

    const matchesFilter =
      filter === "ALL" ||
      (filter === "FRAUD" && item.is_fraud) ||
      (filter === "LEGITIMATE" && !item.is_fraud);

    return matchesSearch && matchesFilter;
  });

  const cardStyle = {
    background: "white",
    padding: "22px",
    borderRadius: "12px",
    boxShadow: "0 2px 8px rgba(0,0,0,0.06)",
  };

  const buttonStyle = {
    padding: "9px 15px",
    borderRadius: "7px",
    border: "none",
    background: "#2563eb",
    color: "white",
    cursor: "pointer",
  };

  return (
    <div className="dashboard-page">

      <div className="page-header">
        <div>
          <h1>AI Prediction History</h1>
          <p>
            Monitor and manage predictions generated by the AEGISAI model.
          </p>
        </div>

        <button style={buttonStyle} onClick={fetchPredictions}>
          Refresh
        </button>
      </div>

      {/* Summary Cards */}

      <div className="summary-cards">

        <div className="summary-card">
          <h3>Total Predictions</h3>
          <h2>{predictions.length}</h2>
          <p>All saved AI predictions</p>
        </div>

        <div className="summary-card">
          <h3>Fraud Detected</h3>
          <h2 style={{ color: "#dc2626" }}>
            {fraudCount}
          </h2>
          <p>Potential fraudulent transactions</p>
        </div>

        <div className="summary-card">
          <h3>Legitimate</h3>
          <h2 style={{ color: "#16a34a" }}>
            {legitimateCount}
          </h2>
          <p>Transactions classified as legitimate</p>
        </div>

      </div>

      {/* Prediction Table */}

      <div className="dashboard-box">

        <div className="box-header">
          <div>
            <h2>Saved Predictions</h2>
            <p>Previously analyzed transactions</p>
          </div>
        </div>

        {/* Search and Filter */}

        <div
          style={{
            display: "flex",
            gap: "12px",
            flexWrap: "wrap",
            margin: "20px 0",
          }}
        >

          <input
            type="text"
            placeholder="Search Prediction ID..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            style={{
              padding: "11px",
              border: "1px solid #ccc",
              borderRadius: "7px",
              flex: "1",
              minWidth: "180px",
            }}
          />

          <select
            value={filter}
            onChange={(e) => setFilter(e.target.value)}
            style={{
              padding: "11px",
              borderRadius: "7px",
              border: "1px solid #ccc",
            }}
          >
            <option value="ALL">All Predictions</option>
            <option value="FRAUD">Fraud Only</option>
            <option value="LEGITIMATE">Legitimate Only</option>
          </select>

        </div>

        {loading && <p>Loading predictions...</p>}

        {error && (
          <p style={{ color: "red" }}>
            Error: {error}
          </p>
        )}

        {!loading && !error && filteredPredictions.length === 0 && (
          <p>No matching predictions found.</p>
        )}

        {!loading && !error && filteredPredictions.length > 0 && (

          <div style={{ overflowX: "auto" }}>

            <table
              style={{
                width: "100%",
                borderCollapse: "collapse",
                textAlign: "left",
              }}
            >

              <thead>
                <tr>
                  {[
                    "Prediction ID",
                    "Date & Time",
                    "Prediction",
                    "Fraud Probability",
                    "Risk Score",
                    "Risk Level",
                    "Action",
                  ].map((heading) => (
                    <th
                      key={heading}
                      style={{
                        padding: "14px",
                        borderBottom: "1px solid #ddd",
                        whiteSpace: "nowrap",
                      }}
                    >
                      {heading}
                    </th>
                  ))}
                </tr>
              </thead>

              <tbody>

                {filteredPredictions.map((item) => (

                  <tr key={item.id}>

                    <td style={{ padding: "14px" }}>
                      {item.id}
                    </td>

                    <td style={{ padding: "14px", whiteSpace: "nowrap" }}>
                      {new Date(item.created_at).toLocaleString()}
                    </td>

                    <td style={{ padding: "14px" }}>
                      <strong
                        style={{
                          color: item.is_fraud ? "#dc2626" : "#16a34a",
                        }}
                      >
                        {item.prediction}
                      </strong>
                    </td>

                    <td style={{ padding: "14px" }}>
                      {(item.fraud_probability * 100).toFixed(2)}%
                    </td>

                    <td style={{ padding: "14px" }}>
                      {item.risk_score}
                    </td>

                    <td style={{ padding: "14px" }}>
                      <strong
                        style={{
                          color:
                            item.risk_level === "HIGH"
                              ? "#dc2626"
                              : "#16a34a",
                        }}
                      >
                        {item.risk_level}
                      </strong>
                    </td>

                    <td style={{ padding: "14px" }}>
                      <button
                        style={buttonStyle}
                        onClick={() => setSelectedPrediction(item)}
                      >
                        View Details
                      </button>
                    </td>

                  </tr>

                ))}

              </tbody>

            </table>

          </div>

        )}

      </div>

      {/* Prediction Details */}

      {selectedPrediction && (

        <div
          style={{
            position: "fixed",
            inset: 0,
            background: "rgba(0,0,0,0.55)",
            display: "flex",
            justifyContent: "center",
            alignItems: "center",
            padding: "20px",
            zIndex: 1000,
          }}
          onClick={() => setSelectedPrediction(null)}
        >

          <div
            style={{
              background: "white",
              padding: "25px",
              borderRadius: "12px",
              width: "100%",
              maxWidth: "650px",
              maxHeight: "85vh",
              overflowY: "auto",
            }}
            onClick={(e) => e.stopPropagation()}
          >

            <h2>Prediction Details</h2>

            <p>
              <strong>Prediction ID:</strong>{" "}
              {selectedPrediction.id}
            </p>

            <p>
              <strong>Prediction:</strong>{" "}
              {selectedPrediction.prediction}
            </p>

            <p>
              <strong>Fraud Probability:</strong>{" "}
              {(selectedPrediction.fraud_probability * 100).toFixed(2)}%
            </p>

            <p>
              <strong>Risk Score:</strong>{" "}
              {selectedPrediction.risk_score}
            </p>

            <p>
              <strong>Risk Level:</strong>{" "}
              {selectedPrediction.risk_level}
            </p>

            <p>
              <strong>Detection Threshold:</strong>{" "}
              {selectedPrediction.threshold}
            </p>

            <h3>Transaction Features</h3>

            <div
              style={{
                display: "grid",
                gridTemplateColumns: "1fr 1fr",
                gap: "10px",
              }}
            >

              {Object.entries(
                selectedPrediction.transaction_features || {}
              ).map(([key, value]) => (

                <div
                  key={key}
                  style={{
                    padding: "10px",
                    background: "#f3f4f6",
                    borderRadius: "6px",
                  }}
                >
                  <strong>{key}:</strong> {value}
                </div>

              ))}

            </div>

            <button
              style={{
                ...buttonStyle,
                marginTop: "20px",
                background: "#dc2626",
              }}
              onClick={() => setSelectedPrediction(null)}
            >
              Close
            </button>

          </div>

        </div>

      )}

    </div>
  );
}

export default PredictionHistory;